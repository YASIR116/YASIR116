"""Generate assets/generated/stats.svg from the GitHub GraphQL API (no third-party widget service).
Runs in GitHub Actions with the built-in GITHUB_TOKEN. Usage: python tools/generate_stats.py [out.svg]"""
import os, sys, json, datetime, urllib.request
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import design as D

QUERY = """query($login:String!){ user(login:$login){ createdAt followers{totalCount}
 repositories(ownerAffiliations:OWNER,isFork:false,privacy:PUBLIC,first:100){ totalCount nodes{ stargazerCount
  languages(first:10,orderBy:{field:SIZE,direction:DESC}){ edges{ size node{ name } } } } }
 pullRequests{totalCount}
 contributionsCollection{ totalCommitContributions contributionCalendar{ totalContributions } } } }"""

def fetch(login, token):
    req = urllib.request.Request("https://api.github.com/graphql", json.dumps({"query": QUERY, "variables": {"login": login}}).encode(),
                                 {"Authorization": f"bearer {token}", "Content-Type": "application/json", "User-Agent": "profile-stats"})
    data = json.load(urllib.request.urlopen(req, timeout=30))
    if "errors" in data: raise RuntimeError(data["errors"])
    return data["data"]["user"]

def summarise(u):
    langs = {}
    for r in u["repositories"]["nodes"]:
        for e in r["languages"]["edges"]: langs[e["node"]["name"]] = langs.get(e["node"]["name"], 0) + e["size"]
    tot = sum(langs.values()) or 1
    top = sorted(langs.items(), key=lambda kv: -kv[1])[:5]
    return {"repos": u["repositories"]["totalCount"], "stars": sum(r["stargazerCount"] for r in u["repositories"]["nodes"]),
            "contrib": u["contributionsCollection"]["contributionCalendar"]["totalContributions"],
            "commits": u["contributionsCollection"]["totalCommitContributions"], "prs": u["pullRequests"]["totalCount"],
            "langs": [(n, 100 * b / tot) for n, b in top], "since": u["createdAt"][:4]}

RAMP = [D.SCARLET, D.CRIMSON, "#8c1a24", "#5a0a12", "#3b3e45"]
def render(s, stamp):
    W, H = 830, 270
    p = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-label="GitHub statistics">',
         f'<rect width="{W}" height="{H}" rx="10" fill="{D.NEAR}" stroke="{D.GRAPHITE2}"/>',
         f'<defs><radialGradient id="g" cx="760" cy="40" r="360" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="{D.DEEP}" stop-opacity="0.7"/><stop offset="1" stop-color="{D.NEAR}" stop-opacity="0"/></radialGradient></defs>',
         f'<rect width="{W}" height="{H}" rx="10" fill="url(#g)"/>']
    items = [("PUBLIC REPOS", s["repos"]), ("STARS EARNED", s["stars"]), ("CONTRIBUTIONS · 12 MO", s["contrib"]), ("COMMITS · 12 MO", s["commits"])]
    for i, (lab, val) in enumerate(items):
        x, y = 36 + (i % 2) * 190, 70 + (i // 2) * 100
        d, _ = D.text_path("display", str(val), 40, x, y + 36); p.append(f'<path d="{d}" fill="{D.WHITE}"/>')
        d, _ = D.text_path("monobold", lab, 11, x, y, tracking=1.6); p.append(f'<path d="{d}" fill="{D.SCARLET}"/>')
    p.append(f'<rect x="420" y="40" width="1" height="180" fill="{D.GRAPHITE2}"/>')
    d, _ = D.text_path("monobold", "TOP LANGUAGES · PUBLIC REPOS (BY BYTES)", 11, 456, 70, tracking=1.6); p.append(f'<path d="{d}" fill="{D.SCARLET}"/>')
    x0, bw = 456, 340; x = x0
    for i, (n, pc) in enumerate(s["langs"]):
        w = max(2, bw * pc / 100); p.append(f'<rect x="{x:.1f}" y="88" width="{max(w-2,1):.1f}" height="10" rx="2" fill="{RAMP[i % 5]}"/>'); x += w
    for i, (n, pc) in enumerate(s["langs"]):
        y = 130 + i * 26
        p.append(f'<rect x="456" y="{y-9}" width="9" height="9" rx="2" fill="{RAMP[i % 5]}"/>')
        d, _ = D.text_path("sans", n, 15, 476, y); p.append(f'<path d="{d}" fill="{D.WHITE}"/>')
        d, _ = D.text_path("mono", f"{pc:.1f}%", 14, 796, y, anchor="end"); p.append(f'<path d="{d}" fill="{D.MUTED}"/>')
    d, _ = D.text_path("mono", f"generated {stamp} UTC · GitHub GraphQL API · public data only", 11, 36, 252); p.append(f'<path d="{d}" fill="{D.MUTED}"/>')
    p.append("</svg>"); return "\n".join(p)

def pending():
    W, H = 830, 120
    d1, _ = D.text_path("monobold", "GITHUB STATS", 12, 36, 52, tracking=2); d2, _ = D.text_path("sans", "Generated by the “Profile stats” workflow — run it once from the Actions tab.", 16, 36, 84)
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-label="GitHub statistics (awaiting first workflow run)"><rect width="{W}" height="{H}" rx="10" fill="{D.NEAR}" stroke="{D.GRAPHITE2}"/><path d="{d1}" fill="{D.SCARLET}"/><path d="{d2}" fill="{D.MUTED}"/></svg>'

if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "assets/generated/stats.svg"
    if "--pending" in sys.argv: out = sys.argv[1]; D.save(out, pending()); sys.exit()
    if "--demo" in sys.argv:  # rendering test with FAKE numbers - never commit this output
        out = sys.argv[1]; D.save(out, render({"repos": 12, "stars": 3, "contrib": 345, "commits": 210, "prs": 2, "langs": [("Python", 52.1), ("HTML", 20.4), ("PHP", 12), ("CSS", 9), ("JavaScript", 6.5)]}, "DEMO")); sys.exit()
    login = os.environ.get("GITHUB_USER") or os.environ["GITHUB_REPOSITORY_OWNER"]
    s = summarise(fetch(login, os.environ["GITHUB_TOKEN"]))
    D.save(out, render(s, datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")))
    print("wrote", out, s)
